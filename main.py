
速度 = 0
周期 = 0
方向 = 0
名前Y = ""

# 調整用パラメータ
反転しきい値 = 150
運動幅しきい値 = 25
停止時間 = 150
送信間隔 = 50
最低周期 = 50
最高周期 = 350

# 山・谷の測定
山値 = 0
谷値 = 0
山時刻 = 0
谷時刻 = 0
山前値 = 0
谷前値 = 0
山前時刻 = 0
谷前時刻 = 0
山後値 = 0
谷後値 = 0
山後時刻 = -1
谷後時刻 = -1

前回山時刻 = -1
前回谷時刻 = -1
前回極値時刻 = -1
前回反転時刻 = -1

# 放物線補間
def 極値補間(t0, v0, t1, v1, t2, v2):
    h1 = t1 - t0
    h2 = t2 - t1
    if h1 <= 0 or h2 <= 0:
        return t1
    s1 = (v1 - v0) / h1
    s2 = (v2 - v1) / h2
    if s1 == s2:
        return t1
    補正 = (0 - (h2 * s1 + h1 * s2)) / (2 * (s2 - s1))
    if 補正 < (0 - h1) or 補正 > h2:
        return t1
    return t1 + 補正

# 周波数から速度への変換
def 速度変換(測定周期):
    v = 10000 / 測定周期
    if v > 100:
        v = 100
    if v <= 60:
        v = v * 0.5
    elif v <= 90:
        v = 30 + (v - 60) * 2
    return v

# A/Bの識別
if input.button_is_pressed(Button.A):
    名前Y = "AY"
    basic.show_string("A")
else:
    名前Y = "BY"
    basic.show_string("B")

前回Y = input.acceleration(Dimension.Y)
山値 = 前回Y
谷値 = 前回Y
前回測定時刻 = input.running_time()
送信時刻 = 前回測定時刻

強度 = input.acceleration(Dimension.STRENGTH)
最大強度 = 強度
最小強度 = 強度

serial.redirect(SerialPin.USB_TX, SerialPin.USB_RX,
    BaudRate.BAUD_RATE115200)

def on_forever():
    global 速度, 周期, 方向
    global 前回Y, 前回測定時刻
    global 山値, 谷値, 山時刻, 谷時刻
    global 山前値, 谷前値, 山前時刻, 谷前時刻
    global 山後値, 谷後値, 山後時刻, 谷後時刻
    global 前回山時刻, 前回谷時刻
    global 前回極値時刻, 前回反転時刻
    global 最大強度, 最小強度, 送信時刻

    今 = input.running_time()
    y = input.acceleration(Dimension.Y)
    強度 = input.acceleration(Dimension.STRENGTH)

    # 合成加速度の変動幅を測定
    if 強度 > 最大強度:
        最大強度 = 強度
    if 強度 < 最小強度:
        最小強度 = 強度

    # 停止判定
    if 前回反転時刻 >= 0:
        if 今 - 前回反転時刻 >= 停止時間:
            速度 = 0
            方向 = 0
            前回山時刻 = -1
            前回谷時刻 = -1
            前回極値時刻 = -1
            前回反転時刻 = -1
            山値 = y
            谷値 = y
            最大強度 = 強度
            最小強度 = 強度

    if y != 前回Y:

        # 初期方向の検出
        if 方向 == 0:
            if y > 山値:
                山値 = y
            if y < 谷値:
                谷値 = y

            if y - 谷値 >= 反転しきい値:
                方向 = 1
                山値 = y
                山時刻 = 今
                山前値 = 前回Y
                山前時刻 = 前回測定時刻
                山後時刻 = -1

            elif 山値 - y >= 反転しきい値:
                方向 = -1
                谷値 = y
                谷時刻 = 今
                谷前値 = 前回Y
                谷前時刻 = 前回測定時刻
                谷後時刻 = -1

        # 上昇中：山の検出
        elif 方向 == 1:
            if y > 山値:
                山前値 = 前回Y
                山前時刻 = 前回測定時刻
                山値 = y
                山時刻 = 今
                山後時刻 = -1

            elif y < 山値 and 山後時刻 < 0:
                山後値 = y
                山後時刻 = 今

            if 山値 - y >= 反転しきい値:
                t = 山時刻

                if 山後時刻 > 山時刻:
                    t = 極値補間(
                        山前時刻, 山前値,
                        山時刻, 山値,
                        山後時刻, 山後値)

                # 合成加速度の変動幅で判定
                if 最大強度 - 最小強度 >= 運動幅しきい値:
                    if 前回山時刻 >= 0:
                        周期 = t - 前回山時刻
                    elif 前回極値時刻 >= 0:
                        周期 = 2 * (t - 前回極値時刻)
                    else:
                        周期 = 0

                    if 周期 >= 最低周期 and 周期 <= 最高周期:
                        速度 = 速度変換(周期)
                    else:
                        速度 = 0

                    前回山時刻 = t
                    前回極値時刻 = t
                    前回反転時刻 = 今
                else:
                    速度 = 0
                    前回山時刻 = -1
                    前回谷時刻 = -1
                    前回極値時刻 = -1

                方向 = -1
                谷値 = y
                谷時刻 = 今
                谷前値 = 前回Y
                谷前時刻 = 前回測定時刻
                谷後時刻 = -1
                最大強度 = 強度
                最小強度 = 強度

        # 下降中：谷の検出
        else:
            if y < 谷値:
                谷前値 = 前回Y
                谷前時刻 = 前回測定時刻
                谷値 = y
                谷時刻 = 今
                谷後時刻 = -1

            elif y > 谷値 and 谷後時刻 < 0:
                谷後値 = y
                谷後時刻 = 今

            if y - 谷値 >= 反転しきい値:
                t = 谷時刻

                if 谷後時刻 > 谷時刻:
                    t = 極値補間(
                        谷前時刻, 谷前値,
                        谷時刻, 谷値,
                        谷後時刻, 谷後値)

                # 合成加速度の変動幅で判定
                if 最大強度 - 最小強度 >= 運動幅しきい値:
                    if 前回谷時刻 >= 0:
                        周期 = t - 前回谷時刻
                    elif 前回極値時刻 >= 0:
                        周期 = 2 * (t - 前回極値時刻)
                    else:
                        周期 = 0

                    if 周期 >= 最低周期 and 周期 <= 最高周期:
                        速度 = 速度変換(周期)
                    else:
                        速度 = 0

                    前回谷時刻 = t
                    前回極値時刻 = t
                    前回反転時刻 = 今
                else:
                    速度 = 0
                    前回山時刻 = -1
                    前回谷時刻 = -1
                    前回極値時刻 = -1

                方向 = 1
                山値 = y
                山時刻 = 今
                山前値 = 前回Y
                山前時刻 = 前回測定時刻
                山後時刻 = -1
                最大強度 = 強度
                最小強度 = 強度

        前回Y = y
        前回測定時刻 = 今

    # シリアル出力
    if 今 - 送信時刻 >= 送信間隔:
        serial.write_value(名前Y, Math.round(速度))
        送信時刻 = 今

    basic.pause(5)

basic.forever(on_forever)
